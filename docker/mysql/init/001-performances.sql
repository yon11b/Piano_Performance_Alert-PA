CREATE TABLE IF NOT EXISTS performances (
  id VARCHAR(255) NOT NULL PRIMARY KEY,
  locaid VARCHAR(255),
  title VARCHAR(255),
  date_start_unix INT,
  date_finish_unix INT,
  location VARCHAR(255),
  cast VARCHAR(255),
  reserve_start INT,
  reserve_finish INT,
  runtime VARCHAR(255),
  age VARCHAR(255),
  make VARCHAR(255),
  price VARCHAR(255),
  poster VARCHAR(255),
  story LONGTEXT,
  famous_level VARCHAR(16) DEFAULT NULL,
  program LONGTEXT,
  composer TEXT,
  genre VARCHAR(255),
  state VARCHAR(255),
  openrun VARCHAR(255),
  created_time DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_time DATETIME DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  time VARCHAR(255),
  date_start VARCHAR(255),
  date_finish VARCHAR(255),
  save VARCHAR(255) DEFAULT '0'
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
